function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value) && Object.getPrototypeOf(value) === Object.prototype
}

function hasExactKeys(value: Record<string, unknown>, required: readonly string[], optional: readonly string[] = []): boolean {
  const allowed = new Set([...required, ...optional])
  return Object.keys(value).every(key => allowed.has(key)) && required.every(key => Object.hasOwn(value, key))
}

function childExit(child: ChildProcess): Promise<void> {
  return new Promise((resolve, reject) => {
    child.once('error', reject)
    child.once('exit', (code, signal) => {
      if (code === 0) resolve()
      else reject(new Error(`native rollback command exited with ${code === null ? signal ?? 'unknown status' : String(code)}`))
    })
  })
}

async function readNativeUpdateWatchState(path: string): Promise<NativeUpdateWatchState | undefined> {
  let text: string
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(await readNativePrivateRegularBytes(path, 'native update watchdog journal'))
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined
    throw new Error('native update watchdog journal cannot be read', { cause: error })
  }
  let value: unknown
  try {
    value = JSON.parse(text) as unknown
  } catch {
    throw new Error('native update watchdog journal is malformed')
  }
  const state = parseNativeUpdateWatchState(value)
  if (state === undefined) throw new Error('native update watchdog journal is invalid')
  return state
}

/**
 * Parse the private native-install journal fields a detached watchdog must observe.
 * @param value - decoded persisted journal object.
 * @returns the bounded watchdog state, or undefined for an unsupported journal representation.
 */
export function parseNativeUpdateWatchState(value: unknown): NativeUpdateWatchState | undefined {
  if (!isRecord(value) || !hasExactKeys(value, [
    'schemaVersion', 'transactionId', 'phase', 'currentVersion', 'version', 'channel', 'format', 'sha256', 'rollbackFormat', 'rollbackSha256',
  ], ['candidateProcess']) || value.schemaVersion !== 1 || !isSemanticVersion(value.version) || !isUuid(value.transactionId)
    || (value.phase !== 'awaiting-dashboard-health' && value.phase !== 'dashboard-health-checking' && value.phase !== 'rollback-scheduled' && value.phase !== 'applied')
    || (value.candidateProcess !== undefined && !isNativeProcessReference(value.candidateProcess))) {
    return undefined
  }
  if (((value.phase === 'dashboard-health-checking' || value.phase === 'rollback-scheduled') && value.candidateProcess === undefined)
    || (value.phase === 'awaiting-dashboard-health' && value.candidateProcess !== undefined)) {
    return undefined
  }
  return {
    phase: value.phase,
    version: value.version,
    transactionId: value.transactionId,
    ...(value.candidateProcess === undefined ? {} : { candidateProcess: value.candidateProcess }),
  }
}

/** Read one cache-local regular file through a stable no-follow handle before its bytes influence an installer. */
async function readNativePrivateRegularBytes(path: string, label: string): Promise<Buffer> {
  const before = await lstat(path)
  if (!before.isFile() || before.isSymbolicLink() || before.nlink !== 1) {
    throw new Error(`${label} is not a private regular file`)
  }
  const handle = await open(path, process.platform === 'win32'
    ? constants.O_RDONLY
    : constants.O_RDONLY | constants.O_NOFOLLOW)
  try {
    const opened = await handle.stat()
    const after = await lstat(path)
    if (!opened.isFile() || !after.isFile() || after.isSymbolicLink() || opened.nlink !== 1
      || !sameNativeFile(before, opened) || !sameNativeFile(opened, after)) {
      throw new Error(`${label} changed while opening`)
    }
    return await handle.readFile()
  } finally {
    await handle.close()
  }
}

function sameNativeFile(left: Stats, right: Stats): boolean {
  return left.dev === right.dev && left.ino === right.ino && left.nlink === right.nlink
}

/** Write verified bytes into an exclusive private worker directory so later execution never reopens cache paths. */
async function snapshotNativeArtifact(sourcePath: string, bytes: Uint8Array): Promise<NativeArtifactSnapshot> {
  const directory = await mkdtemp(join(tmpdir(), 'harness-desktop-native-artifact-'))
  const path = join(directory, `installer${extname(sourcePath)}`)
  try {
    await writeFile(path, bytes, { flag: 'wx', mode: 0o600 })
  } catch (error) {
    await rm(directory, { recursive: true, force: true })
    throw error
  }
  return {
    path,
    dispose: async () => { await rm(directory, { recursive: true, force: true }) },
  }
}

/** Durably publish one exclusive transaction marker without following an existing name. */
async function writeNativeWatchMarkerFile(path: string, content: string): Promise<void> {
  const temporary = `${path}.staging-${randomUUID()}`
  try {
    const existing = await lstat(path).then(() => true, (error: unknown) => {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false
      throw error
    })
    if (existing) throw new Error('native update watchdog heartbeat already exists')
    const handle = await open(temporary, 'wx', 0o600)
    try {
      await handle.writeFile(content)
      await handle.sync()
    } finally {
      await handle.close()
    }
    await rename(temporary, path)
    await syncNativeDirectory(dirname(path))
  } finally {
    await rm(temporary, { force: true })
  }
}

/** Persist one private directory entry that a candidate restart uses to distinguish a live worker from stale recovery state. */
async function syncNativeDirectory(path: string): Promise<void> {
  const handle = await open(path, process.platform === 'win32' ? 'a+' : constants.O_RDONLY)
  try {
    await handle.sync()
  } finally {
    await handle.close()
  }
}

function nativeRun(command: string, args: readonly string[]): Promise<void> {
  return childExit(spawn(command, args, { windowsHide: true, stdio: 'ignore' }))
}

function nativeLaunch(command: string): NativeProcessReference {
  const environment = { ...process.env }
  delete environment.ELECTRON_RUN_AS_NODE
  const child = spawn(command, [], { detached: true, stdio: 'ignore', windowsHide: true, env: environment })
  if (child.pid === undefined) throw new Error('native rollback worker could not identify the candidate process')
  const linuxStartTicks = process.platform === 'linux' ? linuxProcessStartTicks(child.pid) : undefined
  if (process.platform === 'linux' && linuxStartTicks === undefined) {
    child.kill('SIGKILL')
    throw new Error('native rollback worker could not bind the Linux candidate process identity')
  }
  const reference: NativeProcessReference = {
    processId: child.pid,
    executablePath: command,
    startedBeforeMs: Date.now(),
    ...(linuxStartTicks === undefined ? {} : { linuxStartTicks }),
    ...(process.platform === 'win32' ? {} : { processGroupId: child.pid }),
  }
  child.unref()
  return reference
}

const currentLinuxStartTicks = process.platform === 'linux' ? linuxProcessStartTicks(process.pid) : undefined
const currentProcessReference: NativeProcessReference = Object.freeze({
  processId: process.pid,
  executablePath: process.execPath,
  startedBeforeMs: Math.ceil(Date.now() - process.uptime() * 1000),
  ...(currentLinuxStartTicks === undefined ? {} : { linuxStartTicks: currentLinuxStartTicks }),
})

/** @returns the immutable identity for this one Main process, including its startup bound. */
export function currentNativeProcessReference(): NativeProcessReference { return currentProcessReference }

/** @param value - decoded process reference. @returns whether the reference has the exact trusted worker grammar. */
export function isNativeProcessReference(
  value: unknown,
  platform?: NativeRollbackPlan['platform'],
): value is NativeProcessReference {
  return isRecord(value) && hasExactKeys(value, ['processId', 'executablePath', 'startedBeforeMs'], ['linuxStartTicks', 'processGroupId'])
    && isPositiveInteger(value.processId) && typeof value.executablePath === 'string'
    && (platform === undefined ? isAbsolute(value.executablePath) : nativePath(platform).isAbsolute(value.executablePath))
    && typeof value.startedBeforeMs === 'number' && Number.isSafeInteger(value.startedBeforeMs) && value.startedBeforeMs > 0
    && (value.linuxStartTicks === undefined || isLinuxStartTicks(value.linuxStartTicks))
    && (value.processGroupId === undefined || (isPositiveInteger(value.processGroupId) && value.processGroupId === value.processId))
}

function nativeProcessIsAlive(reference: NativeProcessReference): boolean {
  if (process.platform !== 'win32' && reference.processGroupId !== undefined) {
    try {
      process.kill(-reference.processGroupId, 0)
      return true
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ESRCH') return false
      throw new Error('native rollback worker cannot inspect the expected process group')
    }
  }
  try {
    process.kill(reference.processId, 0)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ESRCH') return false
    throw new Error('native rollback worker cannot inspect the expected process')
  }
  if (process.platform === 'win32') {
    throw new Error('Windows native rollback must use its external identity-aware worker')
  }
  return process.platform === 'linux' ? linuxProcessMatches(reference) : posixProcessMatches(reference)
}

/** Bind a checking or atomically applied health report to the process launched by this detached worker. */
function matchesLaunchedCandidate(
  platform: NativeRollbackPlan['platform'],
  launched: NativeProcessReference,
  reported: NativeProcessReference,
): boolean {
  if (launched.processId !== reported.processId) return false
  if (platform === 'linux') {
    return launched.linuxStartTicks !== undefined && launched.linuxStartTicks === reported.linuxStartTicks
  }
  return launched.executablePath === reported.executablePath && reported.startedBeforeMs <= launched.startedBeforeMs
}

/** Compare Linux processes by the kernel start token because an AppImage changes `/proc/<pid>/exe` after `exec`. */
function linuxProcessMatches(reference: NativeProcessReference): boolean {
  return reference.linuxStartTicks !== undefined && linuxProcessStartTicks(reference.processId) === reference.linuxStartTicks
}

/** @returns Linux `/proc/<pid>/stat` field 22, which uniquely binds a PID until reboot. */
function linuxProcessStartTicks(processId: number): string | undefined {
  let content: string
  try {
    content = readFileSync(`/proc/${String(processId)}/stat`, 'utf8')
  } catch {
    return undefined
  }
  const closingParenthesis = content.lastIndexOf(')')
  if (closingParenthesis === -1) return undefined
  const token = content.slice(closingParenthesis + 1).trim().split(/\s+/u)[19]
  return token !== undefined && isLinuxStartTicks(token) ? token : undefined
}

function posixProcessMatches(reference: NativeProcessReference): boolean {
  const ps = process.platform === 'darwin' ? '/bin/ps' : '/usr/bin/ps'
  let output: string
  try {
    output = execFileSync(ps, ['-p', String(reference.processId), '-o', 'lstart=', '-o', 'args='], {
      encoding: 'utf8',
      env: { LC_ALL: 'C', LANG: 'C' },
      stdio: ['ignore', 'pipe', 'ignore'],
      windowsHide: true,
    })
  } catch {
    return false
  }
  const match = output.trim().match(/^(\w{3}\s+\w{3}\s+\d{1,2}\s+\d{2}:\d{2}:\d{2}\s+\d{4})\s+(.+)$/u)
  if (match?.[1] === undefined || match[2] === undefined) throw new Error('native rollback worker cannot parse process identity')
  const startedAt = Date.parse(match[1])
  if (!Number.isFinite(startedAt) || startedAt > reference.startedBeforeMs) return false
  return match[2] === reference.executablePath || match[2].startsWith(`${reference.executablePath} `)
}

const nativeRollbackOperations: NativeRollbackOperations = {
  isProcessAlive: nativeProcessIsAlive,
  terminate: (reference) => {
    if (nativeProcessIsAlive(reference)) terminateNativeProcessTree(reference, 'SIGTERM')
  },
  forceTerminate: (reference) => {
    if (nativeProcessIsAlive(reference)) terminateNativeProcessTree(reference, 'SIGKILL')
  },
  now: () => performance.now(),
  delay: milliseconds => new Promise((resolve) => { setTimeout(resolve, milliseconds) }),
  readArtifact: async path => await readNativePrivateRegularBytes(path, 'native installer cache'),
  snapshotArtifact: snapshotNativeArtifact,
  readWatchState: readNativeUpdateWatchState,
  writeWatchHeartbeat: writeNativeWatchMarkerFile,
  writeRollbackCompletion: writeNativeWatchMarkerFile,
  run: nativeRun,
  launch: nativeLaunch,
  mkdtemp,
  readdir: async path => await readdir(path, { withFileTypes: true }),
  rename,
  copyFile,
  chmod,
  stat,
  remove: async (path) => { await rm(path, { recursive: true, force: true }) },
}

/** Kill the detached POSIX process group created for a verified native candidate. */
function terminateNativeProcessTree(reference: NativeProcessReference, signal: NodeJS.Signals): void {
  if (reference.processGroupId === undefined) {
    try { process.kill(reference.processId, signal) } catch {}
    return
  }
  try {
    process.kill(-reference.processGroupId, signal)
  } catch {
    try { process.kill(reference.processId, signal) } catch {}
  }
}
