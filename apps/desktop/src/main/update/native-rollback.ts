const parentExitPollMs = 100

/**
 * One process identity that rejects a recycled numeric process identifier.
 * The creation bound is generated by the process itself before it launches a detached worker.
 */
export interface NativeProcessReference {
  /** Operating-system process identifier. */
  readonly processId: number
  /** Absolute executable or launcher path associated with the expected process. */
  readonly executablePath: string
  /** Epoch millisecond upper bound for the expected process creation time. */
  readonly startedBeforeMs: number
  /** Linux kernel start-time token, retained when an AppImage launcher can `exec` into a mounted payload. */
  readonly linuxStartTicks?: string
  /** POSIX process-group identifier created for a detached candidate launch. */
  readonly processGroupId?: number
}

/** One private rollback request handed from Main to its detached local worker. */
export interface NativeRollbackPlan {
  /** Wire version for the detached local worker. */
  readonly schemaVersion: 1
  /** Native platform that selects a verifier-approved installer operation. */
  readonly platform: 'win32' | 'darwin' | 'linux'
  /** Main process that must exit before any installed bytes are replaced. */
  readonly parentProcess: NativeProcessReference
  /** Current packaged executable used only to relaunch the restored application. */
  readonly applicationPath: string
  /** AppImage path when the running Linux package is a self-contained AppImage. */
  readonly appImagePath?: string
  /** Locally cached, manifest-verified rollback artifact. */
  readonly rollbackArtifactPath: string
  /** SHA-256 digest that authenticates the local rollback artifact again before execution. */
  readonly rollbackSha256: string
  /** Native rollback installer format tied to the current platform. */
  readonly rollbackFormat: 'nsis' | 'zip' | 'appimage'
  /** Policy-selected candidate Dashboard health window that also bounds the safe shutdown handoff. */
  readonly healthCheckTimeoutMs: number
  /** Transaction identifier when this rollback settles a retained native-update journal. */
  readonly transactionId?: string
}

/** One detached watchdog request that rolls back a candidate which never becomes healthy. */
export interface NativeUpdateWatchPlan extends NativeRollbackPlan {
  /** Locally cached, manifest-verified candidate installer that this external worker installs itself. */
  readonly candidateArtifactPath: string
  /** SHA-256 digest that the worker rechecks immediately before candidate installation. */
  readonly candidateSha256: string
  /** Candidate installer format, fixed by the selected native platform. */
  readonly candidateFormat: 'nsis' | 'zip' | 'appimage'
  /** Exact private journal written by the native-install adapter. */
  readonly journalPath: string
  /** Candidate version that must be acknowledged before this watchdog exits harmlessly. */
  readonly candidateVersion: string
  /** Bounded time allowed for the candidate to load its authenticated Dashboard. */
  readonly healthCheckTimeoutMs: number
  /** Immutable transaction identifier that binds this watcher to one journal generation. */
  readonly transactionId: string
}

/** Native process, file, and clock collaborators isolated for rollback tests. */
export interface NativeRollbackOperations {
  /** @param process - expected Main or candidate process. @returns whether this exact process is still alive. */
  isProcessAlive(process: NativeProcessReference): boolean
  /** @param process - unhealthy candidate Main process. @returns after a checked platform termination request. */
  terminate(process: NativeProcessReference): void
  /** @param process - candidate that ignored a graceful termination request. @returns after a checked forceful termination request. */
  forceTerminate(process: NativeProcessReference): void
  /** @returns monotonic wall-clock milliseconds used only for the bounded watchdog deadline. */
  now(): number
  /** @param milliseconds - bounded polling delay. @returns fulfillment after the delay. */
  delay(milliseconds: number): Promise<void>
  /** @param path - locally cached artifact. @returns bytes used for digest validation. */
  readArtifact(path: string): Promise<Uint8Array>
  /**
   * @param sourcePath - authenticated cache path.
   * @param bytes - verified installer bytes.
   * @returns private executable or archive copy used exactly once.
   */
  snapshotArtifact(sourcePath: string, bytes: Uint8Array): Promise<NativeArtifactSnapshot>
  /**
   * @param path - private native-update journal.
   * @returns validated watchdog state, or undefined only when the journal was removed unexpectedly.
   */
  readWatchState(path: string): Promise<NativeUpdateWatchState | undefined>
  /**
   * @param path - transaction-specific worker heartbeat.
   * @param content - exact transaction-bound worker liveness record.
   * @returns settlement after exclusive durable publication.
   */
  writeWatchHeartbeat(path: string, content: string): Promise<void>
  /**
   * @param path - transaction-specific rollback completion marker.
   * @param content - exact transaction record.
   * @returns settlement after exclusive durable publication.
   */
  writeRollbackCompletion(path: string, content: string): Promise<void>
  /** @param command - absolute executable path. @param args - fixed native updater arguments. @returns exit settlement. */
  run(command: string, args: readonly string[]): Promise<void>
  /**
   * @param command - restored or candidate application executable.
   * @returns exact detached process identity after launch ownership transfers.
   */
  launch(command: string): NativeProcessReference
  /** @param prefix - staging-directory prefix on the destination volume. @returns created private staging directory. */
  mkdtemp(prefix: string): Promise<string>
  /** @param path - directory to enumerate. @returns direct native entries. */
  readdir(path: string): Promise<readonly NativeDirectoryEntry[]>
  /** @param from - source path. @param to - destination path. @returns settlement after an atomic same-volume move. */
  rename(from: string, to: string): Promise<void>
  /** @param from - source artifact. @param to - exact temporary replacement path. @returns settlement after a byte copy. */
  copyFile(from: string, to: string): Promise<void>
  /** @param path - replacement AppImage path. @param mode - exact executable mode. @returns settlement after mode repair. */
  chmod(path: string, mode: number): Promise<void>
  /** @param path - candidate replacement. @returns filesystem metadata used to reject directories. */
  stat(path: string): Promise<{ readonly isFile: () => boolean }>
  /** @param path - exact private staging or retained path. @returns fulfillment when absent or removed. */
  remove(path: string): Promise<void>
}

/** Minimal journal state relevant to a detached watchdog. */
export interface NativeUpdateWatchState {
  /** Lifecycle phase written by the Main-owned native installer adapter. */
  readonly phase: 'awaiting-dashboard-health' | 'dashboard-health-checking' | 'rollback-scheduled' | 'applied'
  /** Candidate version associated with this one native installer transaction. */
  readonly version: string
  /** Immutable transaction identifier associated with this one native installer transaction. */
  readonly transactionId: string
  /** Candidate Main process after it has reached the first health-check write; retained through application acknowledgement. */
  readonly candidateProcess?: NativeProcessReference
}

/** Terminal result of one detached candidate watchdog. */
export type NativeUpdateWatchOutcome = 'applied' | 'rolled-back' | 'unchanged'

/** Direct directory information required by the macOS zip extraction path. */
export interface NativeDirectoryEntry {
  /** Basename without a parent path. */
  readonly name: string
  /** @returns whether this entry is a directory. */
  isDirectory(): boolean
}

/** One private worker-owned copy of an already verified native installer. */
export interface NativeArtifactSnapshot {
  /** Absolute private installer copy passed to a local native installer or replacement operation. */
  readonly path: string
  /** Removes the private copy after the installer operation has stopped using it. */
  dispose(): Promise<void>
}

/**
 * Private installer copies retained by a detached worker before Main is permitted to exit.
 * The worker owns disposal so a recovery path never has to reopen the mutable updater cache.
 */
export interface PreparedNativeRollbackArtifacts {
  /** Verified stable installer copy used for every rollback path in this transaction. */
  readonly rollback: NativeArtifactSnapshot
  /** Verified candidate installer copy when the worker is supervising an update. */
  readonly candidate?: NativeArtifactSnapshot
  /** Releases all worker-owned private copies after the worker reaches a terminal outcome. */
  dispose(): Promise<void>
}

/**
 * Execute exactly one verified rollback after the failed Main process exits.
 * @param plan - authenticated local installer and current installation information.
 * @param operations - native side effects; production defaults run only fixed local commands.
 * @param prepared - worker-owned snapshots already retained before Main exited.
 * @returns fulfillment after the restored application has been launched.
 */
export async function executeNativeRollback(
  plan: NativeRollbackPlan,
  operations: NativeRollbackOperations = nativeRollbackOperations,
  prepared?: PreparedNativeRollbackArtifacts,
  beforeStableLaunch?: () => Promise<void>,
): Promise<void> {
  validatePlan(plan)
  if (!await waitForParentExit(plan.parentProcess, plan.healthCheckTimeoutMs, operations)) {
    throw new Error('native rollback current application did not exit before the safe handoff deadline')
  }
  const rollback = prepared?.rollback ?? await snapshotVerifiedRollbackArtifact(plan, operations)
  try {
    if (plan.platform === 'win32') {
      await operations.run(rollback.path, ['/S'])
      await beforeStableLaunch?.()
      operations.launch(plan.applicationPath)
      return
    }
    if (plan.platform === 'darwin') {
      await restoreMacZip(rollback.path, plan.applicationPath, operations)
      await beforeStableLaunch?.()
      operations.launch(plan.applicationPath)
      return
    }
    await restoreLinuxAppImage(rollback.path, plan, operations)
    await beforeStableLaunch?.()
    operations.launch(plan.appImagePath ?? plan.applicationPath)
  } finally {
    if (prepared === undefined) await rollback.dispose()
  }
}

/**
 * Supervise a scheduled native update outside the candidate application process.
 * @param plan - verified rollback artifact and private health journal.
 * @param operations - detached-process effects; defaults never consume remote release data.
 * @param prepared - worker-owned snapshots already retained before Main exited.
 * @returns fulfillment after health succeeds, a manual rollback supersedes this worker, or rollback relaunches the stable app.
 */
export async function superviseNativeUpdate(
  plan: NativeUpdateWatchPlan,
  operations: NativeRollbackOperations = nativeRollbackOperations,
  prepared?: PreparedNativeRollbackArtifacts,
): Promise<NativeUpdateWatchOutcome> {
  if (prepared === undefined) await verifyNativeRollbackReadiness(plan, operations)
  else {
    validateWatchPlan(plan)
    if (prepared.candidate === undefined) throw new Error('native update watchdog is missing its prepared candidate installer')
  }
  if (!await waitForParentExitBeforeCandidate(plan.parentProcess, plan.healthCheckTimeoutMs, operations)) return 'unchanged'
  let beforeInstall: NativeUpdateWatchState
  try {
    const state = await operations.readWatchState(plan.journalPath)
    if (state === undefined) throw new Error('native update watchdog journal disappeared before candidate installation')
    if (state.version !== plan.candidateVersion || state.transactionId !== plan.transactionId) {
      throw new Error('native update watchdog journal transaction changed before candidate installation')
    }
    beforeInstall = state
  } catch {
    await executeWatchedRollback(plan, operations, prepared)
    return 'rolled-back'
  }
  if (beforeInstall.phase === 'applied') return 'applied'
  if (beforeInstall.phase !== 'awaiting-dashboard-health') {
    await terminateJournalCandidate(beforeInstall, plan.healthCheckTimeoutMs, operations)
    await executeWatchedRollback(plan, operations, prepared)
    return 'rolled-back'
  }
  let candidateProcess: NativeProcessReference | undefined
  try {
    candidateProcess = await installNativeCandidate(plan, operations, prepared?.candidate)
  } catch {
    await executeWatchedRollback(plan, operations, prepared)
    return 'rolled-back'
  }
  if (candidateProcess === undefined) {
    operations.launch(stableApplicationPath(plan))
    return 'unchanged'
  }
  try {
    await writeNativeWatchHeartbeat(plan, operations)
  } catch {
    if (operations.isProcessAlive(candidateProcess)) {
      await terminateCandidateBeforeRollback(candidateProcess, plan.healthCheckTimeoutMs, operations)
    }
    await executeWatchedRollback(plan, operations, prepared)
    return 'rolled-back'
  }
  const deadline = operations.now() + plan.healthCheckTimeoutMs
  while (operations.now() < deadline) {
    let state: NativeUpdateWatchState | undefined
    try {
      state = await operations.readWatchState(plan.journalPath)
      if (state === undefined) throw new Error('native update watchdog journal disappeared before health acknowledgement')
      if (state.version !== plan.candidateVersion || state.transactionId !== plan.transactionId) {
        throw new Error('native update watchdog journal transaction changed')
      }
    } catch {
      break
    }
    if (state.phase === 'dashboard-health-checking') {
      const reported = state.candidateProcess
      if (reported === undefined || !matchesLaunchedCandidate(plan.platform, candidateProcess, reported)) break
      candidateProcess = {
        ...reported,
        ...(candidateProcess.processGroupId === undefined ? {} : { processGroupId: candidateProcess.processGroupId }),
      }
    }
    if (state.phase === 'applied') {
      const reported = state.candidateProcess
      if (reported !== undefined && matchesLaunchedCandidate(plan.platform, candidateProcess, reported)) return 'applied'
      break
    }
    if (state.phase === 'rollback-scheduled') return 'unchanged'
    if (!operations.isProcessAlive(candidateProcess)) break
    await operations.delay(parentExitPollMs)
  }
  if (operations.isProcessAlive(candidateProcess)) {
    await terminateCandidateBeforeRollback(candidateProcess, plan.healthCheckTimeoutMs, operations)
  }
  await executeWatchedRollback(plan, operations, prepared)
  return 'rolled-back'
}

async function executeWatchedRollback(
  plan: NativeUpdateWatchPlan,
  operations: NativeRollbackOperations,
  prepared?: PreparedNativeRollbackArtifacts,
): Promise<void> {
  await executeNativeRollback(plan, operations, prepared, async () => {
    await operations.writeRollbackCompletion(
      nativeUpdateRolledBackPath(plan.rollbackArtifactPath, plan.transactionId, plan.platform),
      `${plan.transactionId}\n`,
    )
  })
}

/**
 * Verify all local bytes and persisted state before a detached worker reports readiness to Main.
 * @param plan - private rollback or watchdog request.
 * @param operations - native filesystem and process collaborators.
 * @returns fulfillment only when the worker can safely begin supervising the requested transition.
 */
export async function verifyNativeRollbackReadiness(
  plan: NativeRollbackPlan | NativeUpdateWatchPlan,
  operations: NativeRollbackOperations = nativeRollbackOperations,
): Promise<void> {
  if (isWatchPlan(plan)) {
    validateWatchPlan(plan)
    const state = await operations.readWatchState(plan.journalPath)
    if (state === undefined || state.version !== plan.candidateVersion || state.transactionId !== plan.transactionId
      || state.phase !== 'awaiting-dashboard-health') {
      throw new Error('native update watchdog journal is not ready')
    }
  } else {
    validatePlan(plan)
  }
  await verifyRollbackArtifact(plan, operations)
  if (isWatchPlan(plan)) await verifyCandidateArtifact(plan, operations)
  await verifyNativeInstallationDestination(plan, operations)
}

/**
 * Copy every verified installer into worker-owned private storage before Main exits.
 * @param plan - fixed local rollback or update-watch operation.
 * @param operations - native filesystem collaborators used for validation and private snapshots.
 * @returns retained copies that can execute without reopening the native-update cache.
 */
export async function prepareNativeRollbackArtifacts(
  plan: NativeRollbackPlan | NativeUpdateWatchPlan,
  operations: NativeRollbackOperations = nativeRollbackOperations,
): Promise<PreparedNativeRollbackArtifacts> {
  await verifyNativeRollbackReadiness(plan, operations)
  const rollback = await snapshotVerifiedRollbackArtifact(plan, operations)
  let candidate: NativeArtifactSnapshot | undefined
  try {
    if (isWatchPlan(plan)) candidate = await snapshotVerifiedCandidateArtifact(plan, operations)
  } catch (error) {
    await rollback.dispose().catch(() => undefined)
    throw error
  }
  let disposed = false
  return {
    rollback,
    ...(candidate === undefined ? {} : { candidate }),
    dispose: async () => {
      if (disposed) return
      disposed = true
      const results = await Promise.allSettled([
        rollback.dispose(),
        ...(candidate === undefined ? [] : [candidate.dispose()]),
      ])
      const errors: unknown[] = []
      for (const result of results) {
        if (result.status === 'rejected') errors.push(result.reason)
      }
      if (errors.length > 0) throw new AggregateError(errors, 'native rollback worker could not remove private installer snapshots')
    },
  }
}

async function terminateJournalCandidate(
  state: NativeUpdateWatchState,
  timeoutMs: number,
  operations: NativeRollbackOperations,
): Promise<void> {
  const candidate = state.candidateProcess
  if (candidate === undefined || !operations.isProcessAlive(candidate)) return
  await terminateCandidateBeforeRollback(candidate, timeoutMs, operations)
}

/** Stop an unhealthy candidate within a finite configured window before any stable bytes are restored. */
async function terminateCandidateBeforeRollback(
  candidate: NativeProcessReference,
  timeoutMs: number,
  operations: NativeRollbackOperations,
): Promise<void> {
  operations.terminate(candidate)
  if (await waitForParentExitBeforeCandidate(candidate, timeoutMs, operations)) return
  operations.forceTerminate(candidate)
  if (await waitForParentExitBeforeCandidate(candidate, timeoutMs, operations)) return
  throw new Error('native update watchdog could not stop the unhealthy candidate')
}

/**
 * Validate an untrusted JSON worker argument before it names any local process or path.
 * @param value - parsed worker argument.
 * @returns the fixed-format plan, or undefined when the argument is invalid.
 */
export function parseNativeRollbackPlan(value: unknown): NativeRollbackPlan | undefined {
  if (!isRecord(value) || !hasExactKeys(value, [
    'schemaVersion', 'platform', 'parentProcess', 'applicationPath', 'rollbackArtifactPath', 'rollbackSha256', 'rollbackFormat', 'healthCheckTimeoutMs',
  ], ['appImagePath', 'candidateArtifactPath', 'candidateSha256', 'candidateFormat', 'journalPath', 'candidateVersion', 'transactionId'])) return undefined
  if (value.schemaVersion !== 1 || !isNativePlatform(value.platform) || !isNativeProcessReference(value.parentProcess, value.platform)
    || typeof value.applicationPath !== 'string' || typeof value.rollbackArtifactPath !== 'string'
    || typeof value.rollbackSha256 !== 'string' || !isRollbackFormat(value.rollbackFormat) || !isBoundedTimeout(value.healthCheckTimeoutMs)
    || (value.appImagePath !== undefined && typeof value.appImagePath !== 'string')) return undefined
  const plan: NativeRollbackPlan = {
    schemaVersion: 1,
    platform: value.platform,
    parentProcess: value.parentProcess,
    applicationPath: value.applicationPath,
    rollbackArtifactPath: value.rollbackArtifactPath,
    rollbackSha256: value.rollbackSha256,
    rollbackFormat: value.rollbackFormat,
    healthCheckTimeoutMs: value.healthCheckTimeoutMs,
    ...(value.appImagePath === undefined ? {} : { appImagePath: value.appImagePath }),
    ...(value.transactionId === undefined ? {} : { transactionId: value.transactionId as string }),
  }
  try {
    validatePlan(plan)
    return plan
  } catch {
    return undefined
  }
}

/**
 * Validate a detached watchdog's JSON argument before it reads a private journal or executes a local installer.
 * @param value - parsed worker argument.
 * @returns fixed watchdog request, or undefined when any field is outside the narrow worker grammar.
 */
export function parseNativeUpdateWatchPlan(value: unknown): NativeUpdateWatchPlan | undefined {
  const rollback = parseNativeRollbackPlan(value)
  if (rollback === undefined || !isRecord(value)
    || typeof value.candidateArtifactPath !== 'string' || !isPlanPathAbsolute(rollback, value.candidateArtifactPath)
    || typeof value.candidateSha256 !== 'string' || !/^[0-9a-f]{64}$/u.test(value.candidateSha256)
    || !isRollbackFormat(value.candidateFormat)
    || typeof value.journalPath !== 'string' || !isPlanPathAbsolute(rollback, value.journalPath)
    || typeof value.candidateVersion !== 'string' || !isSemanticVersion(value.candidateVersion)
    || typeof value.transactionId !== 'string' || !isUuid(value.transactionId)) return undefined
  const plan: NativeUpdateWatchPlan = {
    ...rollback,
    candidateArtifactPath: value.candidateArtifactPath,
    candidateSha256: value.candidateSha256,
    candidateFormat: value.candidateFormat,
    journalPath: value.journalPath,
    candidateVersion: value.candidateVersion,
    transactionId: value.transactionId,
  }
  try {
    validateWatchPlan(plan)
    return plan
  } catch {
    return undefined
  }
}

async function verifyRollbackArtifact(plan: NativeRollbackPlan, operations: NativeRollbackOperations): Promise<void> {
  await verifiedArtifactBytes(plan.rollbackArtifactPath, plan.rollbackSha256, 'native rollback', operations)
}

async function verifyCandidateArtifact(plan: NativeUpdateWatchPlan, operations: NativeRollbackOperations): Promise<void> {
  await verifiedArtifactBytes(plan.candidateArtifactPath, plan.candidateSha256, 'native candidate', operations)
}

async function snapshotVerifiedRollbackArtifact(
  plan: NativeRollbackPlan,
  operations: NativeRollbackOperations,
): Promise<NativeArtifactSnapshot> {
  const bytes = await verifiedArtifactBytes(plan.rollbackArtifactPath, plan.rollbackSha256, 'native rollback', operations)
  return await operations.snapshotArtifact(plan.rollbackArtifactPath, bytes)
}

async function snapshotVerifiedCandidateArtifact(
  plan: NativeUpdateWatchPlan,
  operations: NativeRollbackOperations,
): Promise<NativeArtifactSnapshot> {
  const bytes = await verifiedArtifactBytes(plan.candidateArtifactPath, plan.candidateSha256, 'native candidate', operations)
  return await operations.snapshotArtifact(plan.candidateArtifactPath, bytes)
}

async function verifiedArtifactBytes(
  path: string,
  expectedDigest: string,
  label: string,
  operations: NativeRollbackOperations,
): Promise<Uint8Array> {
  const details = await operations.stat(path)
  if (!details.isFile()) throw new Error(`${label} artifact is not a file`)
  const bytes = await operations.readArtifact(path)
  if (createHash('sha256').update(bytes).digest('hex') !== expectedDigest) {
    throw new Error(`${label} artifact digest changed`)
  }
  return bytes
}

/** Prove the detached worker can create and clean a same-volume private replacement probe before Main exits. */
async function verifyNativeInstallationDestination(
  plan: NativeRollbackPlan | NativeUpdateWatchPlan,
  operations: NativeRollbackOperations,
): Promise<void> {
  if (plan.platform === 'win32') return
  const destinationParent = plan.platform === 'darwin'
    ? posix.dirname(macApplicationBundle(plan.applicationPath))
    : linuxInstallationParent(plan)
  const targetPath = nativePath(plan.platform)
  let probeDirectory = await operations.mkdtemp(targetPath.join(destinationParent, '.harness-desktop-update-probe-'))
  try {
    if (plan.platform === 'linux') {
      const source = isWatchPlan(plan) ? plan.candidateArtifactPath : plan.rollbackArtifactPath
      const probe = targetPath.join(probeDirectory, 'candidate.AppImage')
      await operations.copyFile(source, probe)
      await operations.chmod(probe, 0o755)
    }
    const renamedProbe = `${probeDirectory}.rename`
    await operations.rename(probeDirectory, renamedProbe)
    probeDirectory = renamedProbe
  } finally {
    await operations.remove(probeDirectory)
  }
}

/** @returns the validated writable parent directory for a Linux AppImage replacement. */
function linuxInstallationParent(plan: NativeRollbackPlan | NativeUpdateWatchPlan): string {
  if (plan.platform !== 'linux' || plan.appImagePath === undefined) {
    throw new Error('native rollback Linux installation path is absent')
  }
  return posix.dirname(plan.appImagePath)
}

/** Install an authenticated candidate outside Main, then return its exact new-process identity. */
async function installNativeCandidate(
  plan: NativeUpdateWatchPlan,
  operations: NativeRollbackOperations,
  prepared?: NativeArtifactSnapshot,
): Promise<NativeProcessReference | undefined> {
  const candidate = prepared ?? await snapshotVerifiedCandidateArtifact(plan, operations)
  try {
    if (plan.platform === 'win32') {
      await operations.run(candidate.path, ['/S'])
      return operations.launch(plan.applicationPath)
    }
    if (plan.platform === 'darwin') {
      if (!await replaceMacZip(candidate.path, plan.applicationPath, false, operations)) return undefined
      return operations.launch(plan.applicationPath)
    }
    if (!await replaceLinuxAppImage(candidate.path, plan, operations)) return undefined
    return operations.launch(plan.appImagePath ?? plan.applicationPath)
  } finally {
    if (prepared === undefined) await candidate.dispose()
  }
}

async function waitForParentExit(
  process: NativeProcessReference,
  timeoutMs: number,
  operations: NativeRollbackOperations,
): Promise<boolean> {
  if (await waitForParentExitBeforeCandidate(process, timeoutMs, operations)) return true
  operations.terminate(process)
  if (await waitForParentExitBeforeCandidate(process, timeoutMs, operations)) return true
  operations.forceTerminate(process)
  return await waitForParentExitBeforeCandidate(process, timeoutMs, operations)
}

/** @returns whether the current installation exited before the policy-selected safe handoff deadline. */
async function waitForParentExitBeforeCandidate(
  process: NativeProcessReference,
  timeoutMs: number,
  operations: NativeRollbackOperations,
): Promise<boolean> {
  const deadline = operations.now() + timeoutMs
  while (operations.isProcessAlive(process)) {
    if (operations.now() >= deadline) return false
    await operations.delay(parentExitPollMs)
  }
  return true
}

async function restoreMacZip(archivePath: string, applicationPath: string, operations: NativeRollbackOperations): Promise<void> {
  if (!await replaceMacZip(archivePath, applicationPath, true, operations)) {
    throw new Error('native rollback could not replace the current macOS application')
  }
}

async function replaceMacZip(
  archivePath: string,
  applicationPath: string,
  allowMissingDestination: boolean,
  operations: NativeRollbackOperations,
): Promise<boolean> {
  const appBundle = macApplicationBundle(applicationPath)
  const parent = posix.dirname(appBundle)
  const staging = await operations.mkdtemp(posix.join(parent, '.harness-desktop-rollback-'))
  try {
    await operations.run('/usr/bin/ditto', ['-x', '-k', archivePath, staging])
    const entries = await operations.readdir(staging)
    const bundles = entries.filter(entry => entry.isDirectory() && entry.name.endsWith('.app'))
    if (bundles.length !== 1 || bundles[0] === undefined) throw new Error('native rollback zip does not contain exactly one application bundle')
    return await replaceMacApplication(posix.join(staging, bundles[0].name), appBundle, allowMissingDestination, operations)
  } finally {
    await operations.remove(staging)
  }
}

async function restoreLinuxAppImage(
  artifactPath: string,
  plan: NativeRollbackPlan,
  operations: NativeRollbackOperations,
): Promise<void> {
  if (!await replaceLinuxAppImage(artifactPath, plan, operations)) {
    throw new Error('native rollback could not replace the current AppImage')
  }
}

async function replaceLinuxAppImage(
  artifactPath: string,
  plan: Pick<NativeRollbackPlan, 'appImagePath'>,
  operations: NativeRollbackOperations,
): Promise<boolean> {
  const destination = plan.appImagePath
  if (destination === undefined) throw new Error('native rollback AppImage path is absent')
  const temporary = `${destination}.rollback-${randomUUID()}`
  try {
    await operations.copyFile(artifactPath, temporary)
    await operations.chmod(temporary, 0o755)
    try {
      await operations.rename(temporary, destination)
      return true
    } catch {
      // POSIX rename either publishes the whole candidate or leaves the live AppImage untouched.
      return false
    }
  } finally {
    await operations.remove(temporary)
  }
}

async function replaceMacApplication(
  replacement: string,
  destination: string,
  allowMissingDestination: boolean,
  operations: NativeRollbackOperations,
): Promise<boolean> {
  const retained = posix.join(posix.dirname(destination), '.harness-desktop-retained.app')
  await operations.remove(retained).catch(() => {
    // A previous atomic replacement may leave only its deterministic backup; the fixed destination remains launchable.
  })
  try {
    await operations.run('/usr/bin/osascript', [
      '-l', 'JavaScript', '-e', macAtomicReplacementProgram,
      destination, replacement, basename(retained),
    ])
  } catch (_error) {
    if (!allowMissingDestination) return false
    try {
      await operations.rename(replacement, destination)
      return true
    } catch {
      return false
    }
  }
  await operations.remove(retained).catch(() => {
    // Atomic replacement already left a complete fixed destination; the deterministic backup is recoverable residue.
  })
  return true
}

const macAtomicReplacementProgram = String.raw`
ObjC.import('Foundation')
function run(argv) {
  const manager = $.NSFileManager.defaultManager
  const error = Ref()
  const result = manager.replaceItemAtURLWithItemAtURLBackupItemNameOptionsResultingItemURLError(
    $.NSURL.fileURLWithPath(argv[0]),
    $.NSURL.fileURLWithPath(argv[1]),
    $(argv[2]),
    0,
    null,
    error,
  )
  if (!result) {
    const message = error[0] ? ObjC.unwrap(error[0].localizedDescription) : 'unknown replacement failure'
    throw new Error(message)
  }
}
`

/** @returns the untouched current installation after a candidate replacement fails before publication. */
function stableApplicationPath(plan: NativeUpdateWatchPlan): string {
  return plan.platform === 'linux' ? plan.appImagePath ?? plan.applicationPath : plan.applicationPath
}

function validatePlan(plan: NativeRollbackPlan): void {
  if (
    !isNativeProcessReference(plan.parentProcess, plan.platform)
    || !isPlanPathAbsolute(plan, plan.applicationPath)
    || !isPlanPathAbsolute(plan, plan.rollbackArtifactPath)
    || !/^[0-9a-f]{64}$/u.test(plan.rollbackSha256)
    || !isBoundedTimeout(plan.healthCheckTimeoutMs)
    || (plan.transactionId !== undefined && !isUuid(plan.transactionId))
  ) {
    throw new Error('native rollback plan is invalid')
  }
  if (plan.platform === 'win32') {
    if (plan.rollbackFormat !== 'nsis' || !plan.applicationPath.endsWith('.exe') || !plan.rollbackArtifactPath.endsWith('.exe')) {
      throw new Error('native rollback Windows plan is invalid')
    }
    return
  }
  if (plan.platform === 'darwin') {
    if (plan.rollbackFormat !== 'zip' || !plan.rollbackArtifactPath.endsWith('.zip')) {
      throw new Error('native rollback macOS plan is invalid')
    }
    void macApplicationBundle(plan.applicationPath)
    return
  }
  if (plan.rollbackFormat !== 'appimage' || plan.appImagePath === undefined || !isPlanPathAbsolute(plan, plan.appImagePath)
    || plan.parentProcess.linuxStartTicks === undefined
    || !plan.rollbackArtifactPath.endsWith('.AppImage')) {
    throw new Error('native rollback Linux plan is invalid')
  }
}

function validateWatchPlan(plan: NativeUpdateWatchPlan): void {
  validatePlan(plan)
  if (!isPlanPathAbsolute(plan, plan.candidateArtifactPath) || !/^[0-9a-f]{64}$/u.test(plan.candidateSha256)
    || plan.candidateFormat !== plan.rollbackFormat || !nativeArtifactPathMatches(plan.candidateArtifactPath, plan.candidateFormat)
    || !isPlanPathAbsolute(plan, plan.journalPath) || !isSemanticVersion(plan.candidateVersion) || !isUuid(plan.transactionId)) {
    throw new Error('native update watchdog plan is invalid')
  }
}

function nativeArtifactPathMatches(path: string, format: NativeUpdateWatchPlan['candidateFormat']): boolean {
  if (format === 'nsis') return path.endsWith('.exe')
  if (format === 'zip') return path.endsWith('.zip')
  return path.endsWith('.AppImage')
}

function macApplicationBundle(applicationPath: string): string {
  const macosDirectory = posix.dirname(applicationPath)
  const contentsDirectory = posix.dirname(macosDirectory)
  const bundle = posix.dirname(contentsDirectory)
  if (basename(macosDirectory) !== 'MacOS' || basename(contentsDirectory) !== 'Contents' || !bundle.endsWith('.app')) {
    throw new Error('native rollback macOS application path is invalid')
  }
  return bundle
}

function basename(path: string): string { return path.replace(/[\\/]+$/u, '').split(/[\\/]/u).at(-1) ?? '' }

function nativePath(platform: NativeRollbackPlan['platform']): typeof posix {
  return platform === 'win32' ? win32 : posix
}

